let LANG = "vi";
try {
  const saved = localStorage.getItem("lang");
  if (saved === "vi" || saved === "en") LANG = saved;
} catch (_) { /* storage blocked: keep the default */ }

const LOCALE = () => (LANG === "vi" ? "vi-VN" : "en-US");

function t(key, params = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.vi[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in params ? String(params[name]) : all));
}

/** Translate a server message: "@key" or "@key:{json}". Anything else is shown as is. */
function tr(message) {
  if (typeof message !== "string" || !message.startsWith("@")) return message;
  const match = message.match(/^@([\w.]+)(?::(.*))?$/s);
  if (!match || !(match[1] in STRINGS.vi)) return message;
  let params = {};
  try { params = match[2] ? JSON.parse(match[2]) : {}; } catch (_) { /* malformed params */ }
  if (match[1] === "ai.field_empty" && params.field) params.field = t(`field.${params.field}`);
  return t(match[1], params);
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const node of root.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll("[data-i18n-ph]")) node.placeholder = t(node.dataset.i18nPh);
  for (const node of root.querySelectorAll("[data-i18n-title]")) node.title = t(node.dataset.i18nTitle);
  for (const node of root.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
  for (const btn of root.querySelectorAll(".lang-switch [data-lang]")) {
    btn.classList.toggle("on", btn.dataset.lang === LANG);
    btn.setAttribute("aria-checked", String(btn.dataset.lang === LANG));
  }
}

function setLang(lang) {
  if (lang === LANG || !STRINGS[lang]) return;
  LANG = lang;
  try { localStorage.setItem("lang", lang); } catch (_) { /* per-device preference only */ }
  applyI18n();
  document.dispatchEvent(new Event("langchange"));
}

applyI18n();
for (const btn of document.querySelectorAll(".lang-switch [data-lang]")) btn.onclick = () => setLang(btn.dataset.lang);
